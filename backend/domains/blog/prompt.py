from domains.blog.constants import MAX_CODE_CHARS_FOR_PROMPT
from domains.blog.schemas import BlogRequest


def build_blog_prompt(request: BlogRequest, code: str) -> str:
    return f"""
당신은 한국 개발자 기술 블로그를 실제 발행 가능한 수준으로 다듬는 시니어 테크니컬 라이터입니다.
아래 GitHub 레포지토리의 실제 파일 내용을 분석해 Velog에 바로 붙여넣을 수 있는 한국어 기술 블로그 초안을 작성해주세요.

포스트 유형: {request.post_type}
레포지토리: {request.github_url}

코드:
{code[:MAX_CODE_CHARS_FOR_PROMPT]}

작성 원칙:
- 먼저 파일 경로, 의존성, 클래스/함수/위젯 이름을 근거로 이 프로젝트가 무엇인지 추론합니다.
- 단순한 코드 요약이 아니라, 개발자가 직접 만든 프로젝트를 소개하는 자연스러운 블로그 글로 작성합니다.
- 프로젝트가 게임이면 게임 규칙, 화면 흐름, 상태 관리, 사용자 상호작용, 점수/정답 처리 같은 게임 자체의 구현을 중심으로 씁니다.
- 프로젝트가 앱이면 사용자 문제, 핵심 기능, 화면 구성, 데이터 흐름, 주요 구현을 중심으로 씁니다.
- 프로젝트가 서버/API이면 엔드포인트, 요청/응답, 외부 연동, 예외 처리를 중심으로 씁니다.
- 제목과 섹션 제목에는 Velog에서 읽기 좋은 마크다운을 사용하되, 목차나 템플릿 안내 문구는 넣지 않습니다.
- 각 섹션은 실제 경험담처럼 문단 중심으로 작성하고, 독자가 왜 이 앱을 만들었는지 공감할 수 있게 씁니다.
- 코드에서 확인 가능한 내용은 구체적으로 연결하고, 확인되지 않는 내용은 단정하지 말고 "확장할 수 있다", "이런 방향으로 볼 수 있다"처럼 표현합니다.
- 파일명과 코드 식별자를 직접 언급하면서 설명합니다.
- 레포지토리 코드에 없는 외부 AI API, FastAPI, 프롬프트 설계, 서버 연동 이야기를 임의로 쓰지 않습니다.
- 가능한 경우 짧은 코드 예시나 요청/응답 예시를 포함하되, 전체 코드를 길게 복붙하지 않습니다.
- 반드시 회고까지 작성하고, 마지막 문장은 완결된 문장으로 끝냅니다.
- 길이가 부족할 것 같으면 각 섹션의 문단 수를 줄이더라도 글의 시작부터 회고까지 자연스럽게 완성합니다.
- 최종 결과는 블로그 본문만 출력하고, 별도 설명이나 사족은 붙이지 않습니다.
- "TL;DR", "목차", "핵심 구현 - 프로젝트의 주요 기능", "핵심 구현 - 상태와 사용자 흐름" 같은 템플릿 느낌의 표현은 사용하지 않습니다.

아래 흐름을 참고하되, 섹션 제목은 프로젝트 성격에 맞게 자연스러운 한국어로 바꿔 작성하세요:

# 제목

검색 유입을 고려해 구체적인 제목을 작성합니다.
예시 톤:
- Flutter로 단어 조합 게임 만들기 - WordBlendingGame
- 상태 관리와 입력 검증으로 단어 게임 구현하기
- GitHub 코드로 살펴보는 프로젝트 구현 과정

## 한눈에 보기

3줄 요약으로 작성합니다.
레포지토리 코드 기준으로 무엇을 만들었는지, 어떤 기술로 만들었는지, 결과가 어땠는지 핵심만 씁니다.

## 왜 이 프로젝트를 만들었나

프로젝트 주제에 맞는 문제의식에서 출발해 작성합니다.
게임이면 어떤 재미나 학습 경험을 만들고 싶었는지, 앱이면 어떤 불편을 해결하고 싶었는지 자연스럽게 풀어냅니다.
독자 공감을 얻는 핵심 섹션이므로 너무 짧게 쓰지 않습니다.

## 사용한 기술과 선택 이유

코드에서 확인되는 기술 스택을 설명합니다.
Flutter/Dart 프로젝트라면 위젯 기반 UI, 상태 관리, 크로스플랫폼 장점을 연결합니다.
다른 스택이면 해당 스택이 프로젝트에 맞는 이유를 설명합니다.
코드에서 확인되지 않는 기술은 쓰지 않습니다.

예시:
사용자 입력 -> 상태 변경 -> 정답/결과 판정 -> 화면 갱신

## 코드로 살펴본 주요 기능

코드에서 확인되는 핵심 기능을 가장 깊게 설명합니다.
게임이면 게임 규칙, 화면, 입력, 정답/점수 처리, 레벨/문제 데이터가 어떻게 연결되는지 설명합니다.
앱이면 주요 화면과 기능 흐름을 설명합니다.
서버/API이면 핵심 엔드포인트와 데이터 흐름을 설명합니다.
확인 가능한 클래스, 함수, 파일 경로를 근거로 씁니다.

## 상태 변화와 사용자 흐름

사용자의 행동이 코드 내부 상태와 화면에 어떻게 반영되는지 설명합니다.
상태 변수, 이벤트 핸들러, 렌더링 흐름, 에러/성공 처리 중 코드에서 확인되는 내용을 중심으로 씁니다.
짧은 코드 예시를 하나 포함합니다.

## 만들면서 고민한 지점

코드 구조에서 추론 가능한 현실적인 고민을 씁니다.
게임이면 난이도 조절, 문제 데이터 관리, UI 피드백, 상태 복잡도, 확장성 같은 트레이드오프를 다룹니다.
앱/서버이면 해당 프로젝트 성격에 맞는 고민을 다룹니다.
장점만 쓰지 말고 선택의 대가도 함께 정리합니다.

## 결과와 회고

실제로 써보면 어떤 점이 편해지는지 정리합니다.
아쉬운 점과 다음에 추가하고 싶은 기능을 씁니다.
마지막에는 GitHub 링크 자리도 포함합니다.

예:
GitHub: {request.github_url}
"""
